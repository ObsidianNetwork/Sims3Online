# make-mod.ps1 — sequential build -> package -> install with hash verification.
#
#   .\scripts\make-mod.ps1              # server-host mod (default); refuses install if TS3W running
#   .\scripts\make-mod.ps1 -SkipInstall # build + package only (TS3 running)
#   .\scripts\make-mod.ps1 -Reload      # build + install + restart dev stack (server + client TS3)
#
# The dev stack loads SimsOnlineServerHostMod in BOTH server TS3 and sandboxed client TS3. -Reload
# stops only tracked dev-stack processes (see .omo/run/*-ts3.pid), installs, then `python scripts/stackctl.py up`.

param(
    [switch]$SkipInstall,
    [switch]$Reload,
    [switch]$NoAutoUp,
    # Build even in another session's quiet window (scripts/stack_claim.py take --quiet).
    [switch]$Force
)

$ErrorActionPreference = "Stop"
$RepoRoot = Split-Path -Parent $PSScriptRoot
$ModRoot = Join-Path $RepoRoot "SimsOnlineServerHostMod"
$RunDir = Join-Path $RepoRoot ".omo\run"
$ManifestPath = Join-Path $RunDir "mod-build.json"

# TS3 pid files written by stackctl.py (see RUN_DIR / *_TS3_PID_FILE in stackctl.py).
# Used by -Reload to stop only the tracked dev-stack TS3 instances before reinstalling.
$ServerTs3PidFile   = Join-Path $RunDir "server-ts3.pid"
$ClientTs3PidFile   = Join-Path $RunDir "client-ts3.pid"
$Client2Ts3PidFile  = Join-Path $RunDir "client2-ts3.pid"
# TS3 process image name (Linux/Wine reports it as TS3W.exe; native Windows as TS3W).
$Ts3ProcessName = if ($IsLinux -or $env:WSL_DISTRO_NAME) { "TS3W.exe" } else { "TS3W" }

function Get-FileSha256([string]$Path) {
    try { (Get-FileHash -Path $Path -Algorithm SHA256).Hash.ToLowerInvariant() }
    catch {
        $algo = [System.Security.Cryptography.SHA256]::Create()
        try {
            $bytes = [System.IO.File]::ReadAllBytes($Path)
            $hash = $algo.ComputeHash($bytes)
            ([System.BitConverter]::ToString($hash) -replace '-','').ToLowerInvariant()
        } finally { $algo.Dispose() }
    }
}

function Get-WorkspaceGitSha {
    Push-Location $RepoRoot
    try {
        $sha = git rev-parse --short HEAD 2>$null
        if ($LASTEXITCODE -ne 0 -or -not $sha) { return "unknown" }
        return $sha.Trim()
    }
    finally {
        Pop-Location
    }
}

# the mod sources' hash (scripts/mod_sources.py), "+dirty" when one differs from the commit. It goes in
# BuildStamp.Sources and the build ledger (.omo/run/mod-builds.jsonl, keyed by the sha@utc stamp that HELLO carries
# into the state files' modBuild), not into WireForm: stackctl's staleness check and BridgeLineCodec parse that.
$Python = if (Get-Command python -ErrorAction SilentlyContinue) { "python" } else { "python3" }

function Get-ModSources {
    try {
        $word = & $Python (Join-Path $PSScriptRoot "mod_sources.py") --stamp 2>$null
        if ($LASTEXITCODE -eq 0 -and $word) { return ([string]$word).Trim() }
    } catch {}
    return "unknown"
}

function Write-BuildStamp([string]$GitSha, [string]$BuiltUtc, [string]$Sources) {
    $stampPath = Join-Path $ModRoot "BuildStamp.cs"
    $content = @"
namespace SimsOnlineServerHost
{
    // Generated by scripts/make-mod.ps1 / build-server-host-mod.ps1 — do not hand-edit.
    internal static class BuildStamp
    {
        public static readonly string GitSha = "$GitSha";
        public static readonly string BuiltUtc = "$BuiltUtc";
        // The mod sources' hash (scripts/mod_sources.py), +dirty when one differs from GitSha.
        public static readonly string Sources = "$Sources";

        public static string WireForm()
        {
            return GitSha + "@" + BuiltUtc;
        }
    }
}
"@
    Set-Content -Path $stampPath -Value $content -Encoding UTF8
}

if ($Reload -and $SkipInstall) {
    throw "-Reload and -SkipInstall are mutually exclusive."
}

# Another session's quiet window (an arms series timing the games): no builds until it ends.
if (-not $Force) {
    & $Python (Join-Path $PSScriptRoot "stack_claim.py") check-quiet
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
}

if (-not $SkipInstall -and -not $Reload -and (Get-Process TS3W, TS3W.exe -ErrorAction SilentlyContinue)) {
    throw @"
TS3W.exe is running. Options:
  python scripts/stackctl.py down       # stop stack, then make-mod
  pwsh -NoProfile -File scripts/make-mod.ps1 -Reload       # stop + rebuild + reinstall + auto-up
  pwsh -NoProfile -File scripts/make-mod.ps1 -SkipInstall  # build + package only
"@
}

$gitSha = Get-WorkspaceGitSha
$builtUtc = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ss'Z'")
$modSources = Get-ModSources
Write-Host "make-mod: git=$gitSha built=$builtUtc sources=$modSources"

Write-BuildStamp $gitSha $builtUtc $modSources

# / T5b: build the swappable handler assembly FIRST and embed it into the shell as a
# generated EmbeddedHandlerAssembly.cs. The shell build (step 1) then globs that .cs in. No cycle:
# the handler references engine DLLs only, never the shell.
Write-Host "step 0/4: build-handlers + embed..."
& (Join-Path $PSScriptRoot "make-handlers.ps1")
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Host "step 1/4: build..."
& (Join-Path $ModRoot "build-server-host-mod.ps1")
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$dllPath = Join-Path $ModRoot "bin\Release\SimsOnlineServerHostMod.dll"
$dllSha = Get-FileSha256 $dllPath
Write-Host "  dll sha256=$dllSha"

# The client presentation module (a second script assembly in the package; reloadable: scripts/presentation_reload.py).
& (Join-Path $PSScriptRoot "build-presentation-module.ps1") | Out-Null
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
Write-Host "  presentation module built"

Write-Host "step 2/4: package..."
& (Join-Path $ModRoot "package-server-host-mod.ps1")
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$packagePath = Join-Path $ModRoot "bin\Release\SimsOnlineServerHostMod.package"
$packageSha = Get-FileSha256 $packagePath
Write-Host "  package sha256=$packageSha"

$UserHomeDir = if ($env:USERPROFILE) { $env:USERPROFILE } else { $HOME }
$installedPath = Join-Path $UserHomeDir "Documents\Electronic Arts\The Sims 3\Mods\Packages\SimsOnlineServerHostMod.package"
$installForce = $false
if ($Reload) {
    Write-Host "reload: stopping dev-stack controllers + server/client TS3..."
    # Inline the Stop-DevStackForModReload logic (was in dev-stack-mod.ps1, now absorbed)
    $myPid = $PID
    $watchedTs3 = @()
    Get-Process SimsOnline.Client -ErrorAction SilentlyContinue | ForEach-Object {
        Stop-Process -Id $_.Id -Force -ErrorAction SilentlyContinue
        Write-Host "stopped client controller ($($_.Id))"
    }
    foreach ($f in @($ClientTs3PidFile, $Client2Ts3PidFile)) {
        if ($f -and (Test-Path $f)) {
            try { $ts3Pid = [int](Get-Content $f); if (Get-Process -Id $ts3Pid -ErrorAction SilentlyContinue) { $watchedTs3 += $ts3Pid; Stop-Process -Id $ts3Pid -Force } } catch {}
            Remove-Item $f -ErrorAction SilentlyContinue
        }
    }
    Get-Process SimsOnline.DedicatedServer -ErrorAction SilentlyContinue | ForEach-Object {
        Stop-Process -Id $_.Id -Force -ErrorAction SilentlyContinue
        Write-Host "stopped server controller ($($_.Id))"
    }
    if ($ServerTs3PidFile -and (Test-Path $ServerTs3PidFile)) {
        try { $ts3Pid = [int](Get-Content $ServerTs3PidFile); if (Get-Process -Id $ts3Pid -ErrorAction SilentlyContinue) { $watchedTs3 += $ts3Pid; Stop-Process -Id $ts3Pid -Force } } catch {}
        Remove-Item $ServerTs3PidFile -ErrorAction SilentlyContinue
    }
    foreach ($p in $watchedTs3) { for ($i = 0; $i -lt 150; $i++) { if (-not (Get-Process -Id $p -ErrorAction SilentlyContinue)) { break }; Start-Sleep -Milliseconds 100 } }
    $otherTs3 = @(Get-Process $Ts3ProcessName -ErrorAction SilentlyContinue | ForEach-Object Id)
    $installForce = ($otherTs3.Count -gt 0)
    if ($installForce) { Write-Host "NOTE: TS3W still running. Installing with -Force." -ForegroundColor Yellow }
    Start-Sleep -Seconds 2
}

if ($SkipInstall) {
    Write-Host "step 3/4: install SKIPPED (-SkipInstall)"
}
else {
    Write-Host "step 3/4: install..."
    if ($installForce) {
        & (Join-Path $ModRoot "install-server-host-mod.ps1") -Force
    }
    else {
        & (Join-Path $ModRoot "install-server-host-mod.ps1")
    }
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    if (-not (Test-Path $installedPath)) {
        throw "Install reported success but package missing at $installedPath"
    }

    $installedSha = Get-FileSha256 $installedPath
    if ($installedSha -ne $packageSha) {
        throw "Installed package hash mismatch (built=$packageSha installed=$installedSha)"
    }
    Write-Host "  installed sha256=$installedSha (matches built package)"

    # Linux/Wine: mirror the freshly-installed package into every client Wine prefix.
    # The server prefix's Documents is symlinked to ~/Documents (so $installedPath already
    # covers it), but ~/.sims3-client and ~/.sims3-client2 have their own independent
    # Documents trees (copied by bootstrap-client-prefix.ps1) that are NOT re-synced when
    # the mod rebuilds. Without this, boot-full / up boots client TS3 with a STALE package.
    if ($IsLinux -or $env:WSL_DISTRO_NAME) {
        $clientPrefixes = @(
            (Join-Path $HOME ".sims3-client"),
            (Join-Path $HOME ".sims3-client2")
        )
        $userName = [Environment]::UserName
        foreach ($prefix in $clientPrefixes) {
            if (-not (Test-Path $prefix)) { continue }
            $dest = Join-Path $prefix "drive_c/users/$userName/Documents/Electronic Arts/The Sims 3/Mods/Packages/SimsOnlineServerHostMod.package"
            $destDir = Split-Path $dest
            if (-not (Test-Path $destDir)) {
                Write-Host "  client prefix $prefix has no Mods/Packages dir -- skipping (run bootstrap-client-prefix.ps1 first)" -ForegroundColor Yellow
                continue
            }
            # Skip if already identical (btrfs reflinked or same inode) to avoid needless writes.
            if (Test-Path $dest) {
                try {
                    $destSha = Get-FileSha256 $dest
                    if ($destSha -eq $packageSha) { continue }
                } catch {}
            }
            Copy-Item -Path $packagePath -Destination $dest -Force
            $destSha = Get-FileSha256 $dest
            if ($destSha -ne $packageSha) {
                throw "Client prefix package hash mismatch (built=$packageSha dest=$destSha at $dest)"
            }
            Write-Host "  mirrored to client prefix: $prefix"
        }
    }
    elseif ($IsWindows) {
    # Windows/Sandboxie: mirror the freshly-installed package into every prepared client box.
    # stackctl launches the client TS3s in Client2Box/Client3Box/Client4Box, whose isolated Sims 3
    # profiles live under <SYSTEMDRIVE>\Sandbox\<user>\<box>\drive\C\Sims\.sims3-client\drive_c\
    # users\<name>\Documents\Electronic Arts\The Sims 3 -- the same layout stackctl.py's
    # _box_has_isolated_profile gates on (Saves + Mods\Resource.cfg present). Without this the
    # boxes keep whatever bootstrap-client-prefix copied once: the live runs measured an
    # Oct-24 client mod for a week without noticing (follow-up brief Part B.5).
        $clientBoxes = @("Client2Box", "Client3Box", "Client4Box")
        foreach ($envBox in @($env:SIMSONLINE_SANDBOXIE_BOX, $env:SIMSONLINE_SANDBOXIE_BOX2, $env:SIMSONLINE_SANDBOXIE_BOX3)) {
            if ($envBox -and $clientBoxes -notcontains $envBox) { $clientBoxes += $envBox }
        }
        $sandboxRoot = Join-Path ($env:SYSTEMDRIVE + "\Sandbox") $env:USERNAME
        foreach ($box in $clientBoxes) {
            $usersRoot = Join-Path $sandboxRoot (Join-Path $box "drive\C\Sims\.sims3-client\drive_c\users")
            if (-not (Test-Path $usersRoot)) { continue }   # box not prepared on this machine
            foreach ($user in (Get-ChildItem $usersRoot -Directory -ErrorAction SilentlyContinue)) {
                $profile = Join-Path $user.FullName "Documents\Electronic Arts\The Sims 3"
                $modsDir = Join-Path $profile "Mods"
                if (-not ((Test-Path (Join-Path $profile "Saves")) -and (Test-Path (Join-Path $modsDir "Resource.cfg")))) { continue }
                $dest = Join-Path $modsDir "Packages\SimsOnlineServerHostMod.package"
                if (Test-Path $dest) {
                    try {
                        if ((Get-FileSha256 $dest) -eq $packageSha) { continue }
                    } catch {}
                } else {
                    New-Item -ItemType Directory -Force (Join-Path $modsDir "Packages") | Out-Null
                }
                Copy-Item -Path $packagePath -Destination $dest -Force
                $destSha = Get-FileSha256 $dest
                if ($destSha -ne $packageSha) {
                    throw "Client box package hash mismatch (built=$packageSha dest=$destSha at $dest)"
                }
                Write-Host "  mirrored to client box: $box (user $($user.Name))"
            }
        }
    }

    # no intro movies on any stack profile (server, Sandboxie boxes, Wine prefixes); they
    # cost ~50 s per boot (warm cache). SIMSONLINE_KEEP_INTROS=1 skips this.
    $python = if (Get-Command python -ErrorAction SilentlyContinue) { "python" } else { "python3" }
    & $python (Join-Path $PSScriptRoot "install_nointro.py")
    if ($LASTEXITCODE -ne 0) { Write-Host "  nointro install failed (boots keep the intro movies)" -ForegroundColor Yellow }
}

New-Item -ItemType Directory -Force $RunDir | Out-Null
$manifest = @{
    gitSha       = $gitSha
    builtUtc     = $builtUtc
    sources      = $modSources
    dllSha256    = $dllSha
    packageSha256 = $packageSha
    installedPath = if ($SkipInstall) { $null } else { $installedPath }
    installedSha256 = if ($SkipInstall) { $null } else { $installedSha }
}
$manifest | ConvertTo-Json | Set-Content -Path $ManifestPath -Encoding UTF8
# the build ledger row (and a dirty build's diff), so a crash's modBuild traces to exact sources.
& $Python (Join-Path $PSScriptRoot "mod_sources.py") --record "$gitSha@$builtUtc" --sources $modSources --dll-sha $dllSha --package-sha $packageSha
if ($LASTEXITCODE -ne 0) { Write-Host "  mod_sources --record failed (the build stands; its sources are not in the ledger)" -ForegroundColor Yellow }

Write-Host ""
Write-Host "make-mod OK. Manifest -> .omo/run/mod-build.json" -ForegroundColor Green
if ($Reload -and -not $NoAutoUp) {
    Write-Host "reload: starting dev stack (server + client TS3)..."
    & python3 (Join-Path $PSScriptRoot "stackctl.py") up --skip-mod-sync
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
}
elseif (-not $SkipInstall) {
    Write-Host "Restart the dev stack so server AND client TS3 load the new package:"
    Write-Host "  .\scripts\make-mod.ps1 -Reload   # recommended"
    Write-Host "restart: python scripts/stackctl.py down && python scripts/stackctl.py up"
}
