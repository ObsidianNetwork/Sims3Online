"""Force a join race and watch the joiner's view of the named Sims' conversations.

Waits for a trigger line in the server log (default: the server sending a client its world, the save of its live state,
`last=send:WorldFileChunk`), then optionally ends the named Sims' conversations on the server before the joiner claims,
and probes the client about once a second from its bridge's first answer until `--settle` seconds past its first
absence detach. Every line goes to <out>/race.log with a UTC time. Both probes are generated for the Sims you name
under .omo/run/act/ (never edit a probe per Sim).

  python scripts/join_race_watch.py --sims Gunther,Iliana,Jennifer,Pablo --out .omo/run/race1
  python scripts/join_race_watch.py --sims Pablo --client 127.0.0.1:34031 --no-end --trigger "joined" --dry-run

Read-only unless the end step runs (`--no-end` skips it). Reply of the view probe: ok=<stale==0>;stale=N;streamBuilt=N;
convs=<Sim>:<members '+'-joined or none>,...  Tests: python -m unittest scripts.join_race_watch_test
"""
from __future__ import annotations

import argparse
import datetime
import re
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import probe_source  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ACT = ROOT / ".omo" / "run" / "act"
DEFAULT_TRIGGER = "last=send:WorldFileChunk"

VIEW_TEMPLATE = """using System;
using System.Collections.Generic;
using System.Text;
using Sims3.Gameplay.Actors;
using Sims3.Gameplay.Core;
using Sims3.Gameplay.Socializing;

namespace SimsOnline.Scratch
{
    // Generated by scripts/join_race_watch.py: who talks with whom for the named Sims, on any game.
    public class JoinRaceViewProbe
    {
        private static readonly string[] Names = __NAMES__;

        public static string Run()
        {
            try
            {
                Dictionary<string, string> held = new Dictionary<string, string>();
                Dictionary<Conversation, bool> seen = new Dictionary<Conversation, bool>();
                int stale = 0;
                int streamBuilt = 0;
                foreach (Sim s in LotManager.Actors)
                {
                    if (s == null || s.SimDescription == null || s.SocialComponent == null) { continue; }
                    Conversation conv = s.SocialComponent.Conversation;
                    if (conv == null) { continue; }
                    if (!seen.ContainsKey(conv))
                    {
                        seen[conv] = true;
                        if (conv.SocialGroupSituation == null) { streamBuilt++; }
                    }
                    List<string> members = new List<string>();
                    bool listed = false;
                    foreach (Sim m in conv.Members)
                    {
                        if (m == s) { listed = true; }
                        members.Add(m == null ? "null" : m.FirstName);
                    }
                    if (!listed) { stale++; }
                    members.Sort(StringComparer.Ordinal);
                    held[s.FirstName] = (listed ? "" : "STALE-") + string.Join("+", members.ToArray());
                }
                StringBuilder sb = new StringBuilder();
                sb.Append(stale == 0 ? "ok=true" : "ok=false").Append(";stale=").Append(stale)
                  .Append(";streamBuilt=").Append(streamBuilt).Append(";convs=");
                for (int i = 0; i < Names.Length; i++)
                {
                    string members;
                    sb.Append(i == 0 ? "" : ",").Append(Names[i]).Append(':')
                      .Append(held.TryGetValue(Names[i], out members) ? members : "none");
                }
                return sb.ToString();
            }
            catch (Exception ex) { return "err=" + ex.GetType().Name + ";msg=" + ex.Message; }
        }
    }
}
"""

END_TEMPLATE = """using System;
using System.Collections.Generic;
using Sims3.Gameplay.Actors;
using Sims3.Gameplay.Core;

namespace SimsOnline.Scratch
{
    // Generated by scripts/join_race_watch.py: leaves every conversation the named Sims hold on this game, so a copy
    // saved earlier is one the game never publishes. Reply: ok=true;had=<who held what, sgs=1 when engine-owned>.
    public class JoinRaceEndProbe
    {
        public static string Run()
        {
            try
            {
                List<string> had = new List<string>();
                string[] names = __NAMES__;
                foreach (string name in names)
                {
                    foreach (Sim s in LotManager.Actors)
                    {
                        if (s == null || s.SimDescription == null || s.FirstName != name || s.SocialComponent == null) { continue; }
                        if (s.SocialComponent.Conversation != null)
                        {
                            List<string> members = new List<string>();
                            if (s.SocialComponent.Conversation.Members != null)
                            {
                                foreach (Sim m in s.SocialComponent.Conversation.Members) { members.Add(m != null ? m.FirstName : "null"); }
                            }
                            members.Sort(StringComparer.Ordinal);
                            had.Add(name + ":" + string.Join("+", members.ToArray())
                                + (s.SocialComponent.Conversation.SocialGroupSituation != null ? "(sgs=1)" : "(sgs=0)"));
                            s.SocialComponent.LeaveConversation();
                        }
                    }
                }
                return "ok=true;had=" + (had.Count == 0 ? "none" : string.Join(",", had.ToArray()));
            }
            catch (Exception ex) { return "err=" + ex.GetType().Name + ";msg=" + ex.Message; }
        }
    }
}
"""


def parse_sims(text: str) -> list[str]:
    names = [n.strip() for n in text.split(",") if n.strip()]
    if not names:
        raise ValueError("--sims needs at least one first name")
    for n in names:
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_'-]*", n):
            raise ValueError(f"not a Sim first name: {n!r}")
    return list(dict.fromkeys(names))


def cs_array(names: list[str]) -> str:
    return "new string[] { " + ", ".join(f'"{n}"' for n in names) + " }"


def render(template: str, names: list[str]) -> str:
    return template.replace("__NAMES__", cs_array(names))


def reply(text: str) -> str:
    """The probe's answer from bridgectl output: the lines after `loaded=`, `key = value` squeezed to `key=value`."""
    lines = text.splitlines()
    i = next((k for k, ln in enumerate(lines) if ln.lstrip().startswith("loaded=")), -1)
    if i < 0:
        return text[-160:].replace("\n", " ")
    return ";".join(re.sub(r"\s*=\s*", "=", ln.strip(), count=1) for ln in lines[i + 1:] if ln.strip())


def absence(extras: str) -> tuple[int, str] | None:
    m = re.search(r"absenceDetached:(\d+)/absenceLast:([^/\s]*)", extras)
    return (int(m.group(1)), m.group(2)) if m else None


def find_trigger(text: str, trigger: str) -> str | None:
    for line in text.splitlines():
        if trigger in line:
            return line.strip()
    return None


def done(first_detach: float | None, now: float, settle: float) -> bool:
    return first_detach is not None and now - first_detach > settle


def parse_args(argv: list[str]) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--sims", required=True, type=parse_sims, help="first names, comma-separated")
    p.add_argument("--out", type=Path, required=True, help="directory for race.log (created)")
    p.add_argument("--server", default="127.0.0.1:34029", help="server admin endpoint")
    p.add_argument("--client", default="127.0.0.1:34030", help="joining client's admin endpoint")
    p.add_argument("--server-log", type=Path, default=ROOT / ".omo" / "run" / "server.log")
    p.add_argument("--trigger", default=DEFAULT_TRIGGER, help="server.log text that marks the moment to act")
    p.add_argument("--no-end", action="store_true", help="do not end the Sims' conversations on the server")
    p.add_argument("--trigger-timeout", type=float, default=400)
    p.add_argument("--client-timeout", type=float, default=400)
    p.add_argument("--settle", type=float, default=45, help="seconds to keep probing after the first absence detach")
    p.add_argument("--dry-run", action="store_true", help="write the probes and print the plan; touch no game")
    return p.parse_args(argv)


def bridge(endpoint: str, *args: str, timeout: int = 30) -> str:
    try:
        p = subprocess.run([sys.executable, "scripts/bridgectl.py", "--endpoint", endpoint, "--timeout", str(timeout), *args],
                           cwd=ROOT, capture_output=True, text=True, timeout=timeout + 15)
        return (p.stdout + p.stderr).strip()
    except Exception as ex:  # noqa: BLE001
        return "err " + type(ex).__name__


def main(argv: list[str]) -> int:
    a = parse_args(argv)
    view = probe_source.write(ACT / "JoinRaceViewProbe.cs", render(VIEW_TEMPLATE, a.sims)).relative_to(ROOT).as_posix()
    end = probe_source.write(ACT / "JoinRaceEndProbe.cs", render(END_TEMPLATE, a.sims)).relative_to(ROOT).as_posix()
    if a.dry_run:
        print(f"view probe {view}\nend probe {end}\nserver {a.server} client {a.client} trigger {a.trigger!r} "
              f"end={'no' if a.no_end else 'yes'} sims={','.join(a.sims)}")
        return 0
    a.out.mkdir(parents=True, exist_ok=True)
    log = open(a.out / "race.log", "a", encoding="utf-8")

    def say(text: str) -> None:
        stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%H:%M:%S.%f")[:-3] + "Z"
        log.write(f"{stamp} {text}\n")
        log.flush()

    start = a.server_log.stat().st_size
    say(f"watch start (server.log offset {start})")
    say("server view: " + reply(bridge(a.server, "probe", view, timeout=60)))
    deadline = time.time() + a.trigger_timeout
    sent = None
    while time.time() < deadline and sent is None:
        with open(a.server_log, encoding="utf-8", errors="replace") as f:
            f.seek(start)
            sent = find_trigger(f.read(), a.trigger)
        if sent is None:
            time.sleep(0.3)
    say("trigger: " + (sent or "NOT SEEN")[:200])
    if not a.no_end:
        say("server end: " + reply(bridge(a.server, "probe", end, timeout=60)))
    say("server view: " + reply(bridge(a.server, "probe", view, timeout=60)))
    first = None
    stop = time.time() + a.client_timeout
    while time.time() < stop:
        r = reply(bridge(a.client, "probe", view, timeout=15))
        if r.startswith("ok="):
            extras = bridge(a.client, "SACS_REPLAY", "00", timeout=10)
            ab = absence(extras)
            say("client: " + r[:260] + " | " + (f"absenceDetached:{ab[0]}/absenceLast:{ab[1]}" if ab else "no extras"))
            if ab and ab[0] > 0 and first is None:
                first = time.time()
                say("first absence detach seen")
        if done(first, time.time(), a.settle):
            break
        time.sleep(1)
    say("server view: " + reply(bridge(a.server, "probe", view, timeout=60)))
    say("watch end")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
