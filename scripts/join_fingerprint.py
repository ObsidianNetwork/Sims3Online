""""reuse if unchanged": the join fingerprint on the server's game, measured and counted.

    python scripts/join_fingerprint.py counters [--all] [--log PATH]                  # the controller's reuse counters
    python scripts/join_fingerprint.py scan NAME [--sims Jennifer,Pablo] [--repeat 3]   # one scan, kept as NAME
    python scripts/join_fingerprint.py diff A B                                       # which parts changed

counters reads the newest "[world] join reuse" line of the server controller's log (.omo/run/server.log of the checkout
that booted the stack; --log for another): the last join's outcome (HIT, or MISS with its reasons), then the hits,
the misses by reason, the scan ms inside the game (last, max), each fresh join checkpoint's save ms (last, max: the
stall every player sees), the saves skipped and the seconds saved (per hit, the last fresh save's time). --all lists
every join. The controller serves the last save to a join when the fingerprint taken in that save equals one taken at
the join (DedicatedServer JoinWorldReuse, SimsOnlineServerHostMod/JoinFingerprint.cs); SIMSONLINE_JOIN_REUSE=0 turns it
off. No stack claim needed: it only reads the log.

A late joiner would get the last checkpoint instead of a fresh save while nothing it can only get from the save has
changed since (internal documentation, Part 1). The fingerprint covers exactly that state, for the player scope
(the households of --sims, their home lots and the lots those Sims are on now):
- objects: every object on those lots but Sims, by id and type, with its spot (0.25 m) when it stands free (not held, not
  in an inventory). Objects bought, sold, deleted, made by play (a plate, a puddle) or moved in build mode have no live
  channel.
- inventories: each inventory of those households' Sims and of those lots' objects, as its item ids. G's Iv poll
  (sim143/mirrored-ui) sends membership near streamed Sims only, and only for items the joiner already has.
- relationships: each relationship of those households' Sims, as the long-term state and the liking in steps of 10.
  No live channel carries relationships.
Left out because a live channel carries it to a joiner: Sim spots, animations and postures (the presentation stream and
its join history), outfits (streamed), motives and moodlets (SimStateChanged), the claimed Sims' jobs, funds and
skills (SimDetailsChanged, sent at a join), new Sims on player lots (SimSpawned), the time (WorldTimeChanged).

scan runs one generated probe on the server's game (bridgectl probe, as persist_cycle does), which scans --repeat times
and reports each part's count, hash and milliseconds (mean and max), plus the whole world's object count and scan time
for comparison. It needs the stack claim. Scans go to .omo/run/persist/fingerprint-NAME.json.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import persist_cycle  # noqa: E402
import sim_compare  # noqa: E402

PARTS = ("objects", "inventories", "relationships", "world")
PROBE = persist_cycle.ROOT / ".omo" / "run" / "act" / "JoinFingerprintProbe.cs"

TEMPLATE = r'''using System;
using System.Collections.Generic;
using System.Text;
using Sims3.Gameplay;
using Sims3.Gameplay.Abstracts;
using Sims3.Gameplay.Actors;
using Sims3.Gameplay.CAS;
using Sims3.Gameplay.Core;
using Sims3.Gameplay.Interfaces;
using Sims3.Gameplay.Socializing;
using Sims3.SimIFace;

namespace SimsOnline.Scratch
{
    // Generated by scripts/join_fingerprint.py: the join fingerprint's parts, "field|part|value".
    public class JoinFingerprintProbe
    {
        private const string Names = "__NAMES__";
        private const int Repeat = __REPEAT__;

        private static ulong Hash(List<string> entries)
        {
            entries.Sort(StringComparer.Ordinal);
            ulong h = 14695981039346656037UL;
            foreach (string entry in entries)
            {
                foreach (char c in entry)
                {
                    h = (h ^ c) * 1099511628211UL;
                }

                h = (h ^ 10) * 1099511628211UL;
            }

            return h;
        }

        private static string Step(float v)
        {
            return ((int)Math.Round(v * 4f)).ToString();
        }

        private static List<string> Objects(List<Lot> lots)
        {
            List<string> entries = new List<string>();
            foreach (Lot lot in lots)
            {
                foreach (GameObject obj in lot.GetObjects<GameObject>())
                {
                    if (obj is Sim)
                    {
                        continue;
                    }

                    string entry = obj.ObjectId.Value.ToString() + ":" + obj.GetType().Name;
                    if (obj.Parent == null && !obj.InInventory)
                    {
                        Vector3 p = obj.Position;
                        entry += ":" + Step(p.x) + "," + Step(p.y) + "," + Step(p.z);
                    }

                    entries.Add(entry);
                }
            }

            return entries;
        }

        private static void AddInventory(List<string> entries, ulong owner, Inventory inventory, ref int items)
        {
            if (inventory == null)
            {
                return;
            }

            List<string> ids = new List<string>();
            foreach (IGameObject item in inventory.FindAllOfType(typeof(IGameObject)))
            {
                ids.Add(item.ObjectId.Value.ToString());
            }

            if (ids.Count == 0)
            {
                return;
            }

            ids.Sort(StringComparer.Ordinal);
            items += ids.Count;
            entries.Add(owner.ToString() + ":" + string.Join(",", ids.ToArray()));
        }

        private static List<string> Inventories(List<Household> households, List<Lot> lots, ref int items)
        {
            List<string> entries = new List<string>();
            foreach (Household household in households)
            {
                foreach (SimDescription d in household.AllSimDescriptions)
                {
                    if (d.CreatedSim != null)
                    {
                        AddInventory(entries, d.CreatedSim.ObjectId.Value, d.CreatedSim.Inventory, ref items);
                    }
                }
            }

            foreach (Lot lot in lots)
            {
                foreach (GameObject obj in lot.GetObjects<GameObject>())
                {
                    if (!(obj is Sim))
                    {
                        AddInventory(entries, obj.ObjectId.Value, obj.Inventory, ref items);
                    }
                }
            }

            return entries;
        }

        private static List<string> Relationships(List<Household> households)
        {
            Dictionary<string, bool> seen = new Dictionary<string, bool>();
            List<string> entries = new List<string>();
            foreach (Household household in households)
            {
                foreach (SimDescription d in household.AllSimDescriptions)
                {
                    foreach (Relationship r in Relationship.GetRelationships(d))
                    {
                        SimDescription other = r.GetOtherSimDescription(d);
                        if (other == null || r.LTR == null)
                        {
                            continue;
                        }

                        ulong a = Math.Min(d.SimDescriptionId, other.SimDescriptionId);
                        ulong b = Math.Max(d.SimDescriptionId, other.SimDescriptionId);
                        string pair = a.ToString() + "-" + b.ToString();
                        if (seen.ContainsKey(pair))
                        {
                            continue;
                        }

                        seen[pair] = true;
                        entries.Add(pair + ":" + r.LTR.CurrentLTR.ToString() + ":" + ((int)Math.Floor(r.LTR.Liking / 10f)).ToString());
                    }
                }
            }

            return entries;
        }

        private static void Report(StringBuilder sb, string part, int count, ulong hash, long totalTicks, long maxTicks)
        {
            sb.Append("\ncount|").Append(part).Append("|").Append(count.ToString());
            sb.Append("\nhash|").Append(part).Append("|").Append(hash.ToString("x16"));
            sb.Append("\nms|").Append(part).Append("|").Append((totalTicks / (double)Repeat / 10000.0).ToString("F2"))
                .Append(" ").Append((maxTicks / 10000.0).ToString("F2"));
        }

        public static string Run()
        {
            StringBuilder sb = new StringBuilder("ok=true");
            try
            {
                List<Household> households = new List<Household>();
                List<Lot> lots = new List<Lot>();
                foreach (Sim sim in Sims3.Gameplay.Queries.GetObjects<Sim>())
                {
                    if (sim.SimDescription == null || Array.IndexOf(Names.Split(','), sim.FirstName) < 0)
                    {
                        continue;
                    }

                    if (sim.Household != null && !households.Contains(sim.Household))
                    {
                        households.Add(sim.Household);
                        if (sim.Household.LotHome != null && !lots.Contains(sim.Household.LotHome))
                        {
                            lots.Add(sim.Household.LotHome);
                        }
                    }

                    if (sim.LotCurrent != null && !lots.Contains(sim.LotCurrent))
                    {
                        lots.Add(sim.LotCurrent);
                    }
                }

                sb.Append("\nscope|-|households=").Append(households.Count.ToString()).Append(" lots=").Append(lots.Count.ToString());
                string[] parts = { "objects", "inventories", "relationships", "world" };
                foreach (string part in parts)
                {
                    int count = 0;
                    ulong hash = 0;
                    long total = 0;
                    long max = 0;
                    for (int i = 0; i < Repeat; i++)
                    {
                        long started = DateTime.UtcNow.Ticks;
                        List<string> entries;
                        int items = 0;
                        if (part == "objects")
                        {
                            entries = Objects(lots);
                        }
                        else if (part == "inventories")
                        {
                            entries = Inventories(households, lots, ref items);
                        }
                        else if (part == "relationships")
                        {
                            entries = Relationships(households);
                        }
                        else
                        {
                            entries = new List<string>();
                            foreach (GameObject obj in Sims3.Gameplay.Queries.GetObjects<GameObject>())
                            {
                                entries.Add(obj.ObjectId.Value.ToString());
                            }
                        }

                        hash = Hash(entries);
                        count = part == "inventories" ? items : entries.Count;
                        long spent = DateTime.UtcNow.Ticks - started;
                        total += spent;
                        max = Math.Max(max, spent);
                    }

                    Report(sb, part, count, hash, total, max);
                }

                return sb.ToString();
            }
            catch (Exception ex)
            {
                return "ok=false;err=" + ex.GetType().Name + ":" + ex.Message.Replace(';', ',') + sb;
            }
        }
    }
}
'''


def probe_text(sims: list[str], repeat: int) -> str:
    return TEMPLATE.replace("__NAMES__", ",".join(sims)).replace("__REPEAT__", str(repeat))


def parse(fields: dict[tuple[str, str], list[str]]) -> dict:
    """run_side's {(part, field): [values]} as {"scope", "errors", part: {count, hash, ms, ms_max}}."""
    scan: dict = {"scope": (fields.get(("-", "scope")) or ["-"])[0], "errors": fields.get(("-", "error"), [])}
    for part in PARTS:
        if (part, "hash") not in fields:
            continue
        mean, top = fields[(part, "ms")][0].split()
        scan[part] = {"count": int(fields[(part, "count")][0]), "hash": fields[(part, "hash")][0],
                      "ms": float(mean), "ms_max": float(top)}
    return scan


def changed(a: dict, b: dict) -> list[str]:
    """The fingerprint parts whose hash differs (the world part is for comparison only and never counts)."""
    return [part for part in PARTS[:3] if part in a and part in b and a[part]["hash"] != b[part]["hash"]]


def print_scan(scan: dict) -> None:
    print(f"scope: {scan['scope']}")
    for part in PARTS:
        if part in scan:
            row = scan[part]
            print(f"  {part:<14} {row['count']:>7}  {row['hash']}  {row['ms']:8.2f} ms (max {row['ms_max']:.2f})")
    total = sum(scan[p]["ms"] for p in PARTS[:3] if p in scan)
    print(f"  one fingerprint scan (objects + inventories + relationships): {total:.2f} ms; a join costs two")
    for error in scan["errors"]:
        print(f"  ERROR {error}")


def path_for(name: str) -> Path:
    return persist_cycle.STORE / f"fingerprint-{name}.json"


def scan_cmd(name: str, sims: list[str], repeat: int) -> int:
    ok, why = persist_cycle.claim_check()
    if not ok:
        print(f"BLOCKED: {why}")
        return 2
    PROBE.parent.mkdir(parents=True, exist_ok=True)
    PROBE.write_text(probe_text(sims, repeat), encoding="utf-8")
    scan = parse(sim_compare.run_side(persist_cycle.SERVER, PROBE))
    persist_cycle.STORE.mkdir(parents=True, exist_ok=True)
    path_for(name).write_text(json.dumps(scan, indent=2), encoding="utf-8")
    print_scan(scan)
    return 1 if scan["errors"] or not all(p in scan for p in PARTS) else 0


def diff_cmd(a: str, b: str) -> int:
    first, second = (json.loads(path_for(n).read_text(encoding="utf-8")) for n in (a, b))
    parts = changed(first, second)
    for part in PARTS[:3]:
        if part in first and part in second:
            print(f"  {part:<14} {first[part]['count']:>7} -> {second[part]['count']:<7} {'CHANGED' if part in parts else 'same'}")
    print("reuse: no (" + ", ".join(parts) + " changed)" if parts else "reuse: yes, nothing a joiner needs changed")
    return 0


JOIN_LINE = re.compile(r"\[world\] join reuse: (HIT|MISS \(([^)]*)\)): (.*) \| (hits=.*)$")
COUNTERS = re.compile(
    r"hits=(\d+) misses=(\d+) \(([^)]*)\) scan-ms last=(\S+) max=(\S+) save-ms last=(\S+) max=(\S+) "
    r"saves-skipped=(\d+) seconds-saved=(\S+)")


def join_lines(text: str) -> list[dict]:
    """Each join's "[world] join reuse" line in a controller log: outcome, reasons, detail, counters."""
    joins = []
    for number, line in enumerate(text.splitlines(), 1):
        found = JOIN_LINE.search(line)
        counters = COUNTERS.search(found.group(4)) if found else None
        if not found or not counters:
            continue
        hits, misses, reasons, scan_last, scan_max, save_last, save_max, skipped, saved = counters.groups()
        joins.append({
            "line": number,
            "outcome": "HIT" if found.group(1) == "HIT" else "MISS",
            "reasons": [r.strip() for r in (found.group(2) or "").split(",") if r.strip()],
            "detail": found.group(3),
            "hits": int(hits),
            "misses": int(misses),
            "by_reason": {k: int(v) for k, v in (pair.split("=") for pair in reasons.split())},
            "scan_ms": (scan_last, scan_max),
            "save_ms": (save_last, save_max),
            "saves_skipped": int(skipped),
            "seconds_saved": float(saved),
        })
    return joins


def print_join(join: dict) -> None:
    print(f"  line {join['line']}: {join['outcome']}" + (f" ({', '.join(join['reasons'])})" if join["reasons"] else "")
          + f": {join['detail']}")


def counters_cmd(log: Path, every: bool) -> int:
    if not log.exists():
        print(f"no controller log at {log}")
        return 1
    joins = join_lines(log.read_text(encoding="utf-8", errors="replace"))
    if not joins:
        print(f"no join reuse lines in {log}: no join since this controller started, or SIMSONLINE_JOIN_REUSE=0")
        return 1
    print(f"join reuse ({log}, {len(joins)} join(s) logged):")
    for join in joins if every else joins[-1:]:
        print_join(join)
    last = joins[-1]
    print(f"  hits {last['hits']}, misses {last['misses']}: "
          + ", ".join(f"{k} {v}" for k, v in last["by_reason"].items()))
    print(f"  scan ms in the game: last {last['scan_ms'][0]}, max {last['scan_ms'][1]}")
    print(f"  fresh join checkpoint save ms: last {last['save_ms'][0]}, max {last['save_ms'][1]}")
    print(f"  saves skipped {last['saves_skipped']}, seconds saved {last['seconds_saved']:.1f}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    counters = sub.add_parser("counters")
    counters.add_argument("--log", type=Path, default=persist_cycle.ROOT / ".omo" / "run" / "server.log")
    counters.add_argument("--all", action="store_true", help="every join, not only the last")
    scan = sub.add_parser("scan")
    scan.add_argument("name")
    scan.add_argument("--sims", default=",".join(persist_cycle.SIMS))
    scan.add_argument("--repeat", type=int, default=3)
    diff = sub.add_parser("diff")
    diff.add_argument("a")
    diff.add_argument("b")
    args = parser.parse_args(argv)
    if args.cmd == "counters":
        return counters_cmd(args.log, args.all)
    if args.cmd == "scan":
        return scan_cmd(args.name, [s for s in args.sims.split(",") if s], max(1, args.repeat))
    return diff_cmd(args.a, args.b)


if __name__ == "__main__":
    raise SystemExit(main())
