"""Each game's families, read in the game itself.

    python scripts/household_read.py                          # server, client 1, client 2: each one's active household
    python scripts/household_read.py Langerak                 # and the Langeraks, on every game
    python scripts/household_read.py Langerak --game client2  # one game (server, client1, client2 or HOST:PORT)
    python scripts/household_read.py --sim Iliana             # a Sim's object id on the server (and its household)
    python scripts/household_read.py --pair Jennifer+Iliana   # two Sims' relationship (liking, state) on every game
    python scripts/household_read.py Langerak --json          # the readings as JSON

TS3 has no active-household setting of its own: Household.ActiveHousehold is the selected Sim's household
(Sim.ActiveActor?.Household, Sims3.Gameplay.CAS/Household.cs:792), so a game's family is whichever family its selected
Sim belongs to. Per game the read gives the selected Sim (first name, SimDescriptionId, household) and, for its
household and each one named, the household's name, HouseholdId, FamilyFunds, home lot (LotId and address) and each
member: first name, SimDescriptionId, the Sim's object id (0 when it is not in the world) and the lot it stands on.
A client's Sims have this game's own object ids; the SimDescriptionId is the same on every game.

--pair A+B (repeatable) reads the relationship of two Sims (first names) in each game: the liking (-100..100) and the
long-term state (Relationship.Get(a, b, false).LTR), or "none" when they have none. No live channel carries
relationships (join_fingerprint.py), so a social on the server can differ from a client's until a join.

--sim NAME finds a Sim by first name on the server (a Sim of a household with a home lot first, as a player's family
is): its object id is the id quick_loop's wait:/until: steps, motion_watch and stackctl's --claim-sim2 take
(sim_id(); quick_loop and motion_watch call it for a first name they have no id for).

One probe per game (bridgectl probe, .omo/run/act/HouseholdReadProbe.cs). It only reads: no stack claim needed.
Tests: python -m unittest scripts.household_read_test
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import compare_client  # noqa: E402
from local_endpoints import SERVER_BRIDGECTL  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PROBE = ROOT / ".omo" / "run" / "act" / "HouseholdReadProbe.cs"
SERVER = SERVER_BRIDGECTL
# The Martinezes' object ids, the same on every boot of this save (quick_loop.SIMS, motion_watch.SIMS).
KNOWN = {"jennifer": "18031287978496800304", "pablo": "18031287978496800272"}

TEMPLATE = r'''using System;
using System.Collections.Generic;
using System.Text;
using Sims3.Gameplay.Actors;
using Sims3.Gameplay.CAS;
using Sims3.Gameplay.Core;
using Sims3.Gameplay.Socializing;

namespace SimsOnline.Scratch
{
    // Generated by scripts/household_read.py: the selected Sim, its household and the named households
    // ("household|<name>|..."), the named Sims ("sim|<first name>|...") and the named pairs' relationships
    // ("pair|<A>+<B>|<liking> <state>").
    public class HouseholdReadProbe
    {
        private const string Households = "__HOUSEHOLDS__";
        private const string Sims = "__SIMS__";
        private const string Pairs = "__PAIRS__";

        private static string Clean(string text)
        {
            if (text == null || text.Length == 0)
            {
                return "-";
            }

            return text.Replace('|', ' ').Replace(';', ' ').Replace(',', ' ').Replace(':', ' ').Replace('\n', ' ');
        }

        private static bool Named(string list, string name)
        {
            foreach (string entry in list.Split(','))
            {
                if (entry.Length > 0 && string.Equals(entry, name, StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }
            }

            return false;
        }

        private static string Member(SimDescription sd)
        {
            Sim sim = sd.CreatedSim;
            return Clean(sd.FirstName) + ":" + sd.SimDescriptionId + ":" + (sim == null ? "0" : sim.ObjectId.Value.ToString())
                + ":" + (sim == null || sim.LotCurrent == null ? "0" : sim.LotCurrent.LotId.ToString()) + ":" + sd.Age;
        }

        private static void Line(StringBuilder sb, Household h, bool active)
        {
            sb.Append("\nhousehold|").Append(Clean(h.Name)).Append("|id=").Append(h.HouseholdId)
                .Append(";funds=").Append(h.FamilyFunds)
                .Append(";home=").Append(h.LotHome == null ? "0" : h.LotHome.LotId.ToString())
                .Append(";address=").Append(h.LotHome == null ? "-" : Clean(h.LotHome.Address))
                .Append(";active=").Append(active ? "1" : "0")
                .Append(";members=");
            bool first = true;
            foreach (SimDescription sd in h.AllSimDescriptions)
            {
                if (sd == null)
                {
                    continue;
                }

                sb.Append(first ? "" : ",").Append(Member(sd));
                first = false;
            }
        }

        // A Sim of a household with a home lot first (a family), as household_read.pick_sim chooses.
        private static SimDescription Find(string name)
        {
            SimDescription found = null;
            foreach (Household h in Household.sHouseholdList)
            {
                if (h == null)
                {
                    continue;
                }

                foreach (SimDescription sd in h.AllSimDescriptions)
                {
                    if (sd != null && string.Equals(sd.FirstName, name, StringComparison.OrdinalIgnoreCase)
                        && (found == null || h.LotHome != null))
                    {
                        found = sd;
                    }
                }
            }

            return found;
        }

        public static string Run()
        {
            StringBuilder sb = new StringBuilder("ok=true");
            try
            {
                Sim actor = Sim.ActiveActor;
                Household mine = actor == null ? null : actor.Household;
                sb.Append("\nactive|-|").Append(actor == null || actor.SimDescription == null ? "-"
                    : Member(actor.SimDescription) + ":" + Clean(mine == null ? "-" : mine.Name));
                if (mine != null)
                {
                    Line(sb, mine, true);
                }

                foreach (Household h in Household.sHouseholdList)
                {
                    if (h == null)
                    {
                        continue;
                    }

                    if (h != mine && Named(Households, h.Name))
                    {
                        Line(sb, h, false);
                    }

                    foreach (SimDescription sd in h.AllSimDescriptions)
                    {
                        if (sd != null && Named(Sims, sd.FirstName))
                        {
                            sb.Append("\nsim|").Append(Clean(sd.FirstName)).Append("|").Append(Member(sd))
                                .Append(":").Append(Clean(h.Name)).Append(":").Append(h.LotHome == null ? "0" : "1");
                        }
                    }
                }

                foreach (string pair in Pairs.Split(','))
                {
                    string[] names = pair.Split('+');
                    if (names.Length != 2)
                    {
                        continue;
                    }

                    SimDescription a = Find(names[0]);
                    SimDescription b = Find(names[1]);
                    Relationship r = a == null || b == null ? null : Relationship.Get(a, b, false);
                    sb.Append("\npair|").Append(Clean(names[0])).Append("+").Append(Clean(names[1])).Append("|")
                        .Append(a == null || b == null ? "missing" : r == null || r.LTR == null ? "none"
                            : r.LTR.Liking.ToString("F1") + " " + r.LTR.CurrentLTR.ToString());
                }

                return sb.ToString();
            }
            catch (Exception ex)
            {
                return "ok=false;err=" + ex.GetType().Name + ":" + ex.Message.Replace(';', ',') + sb;
            }
        }
    }
}
'''


def probe_text(households: list[str], sims: list[str] | None = None, pairs: list[str] | None = None) -> str:
    return (TEMPLATE.replace("__HOUSEHOLDS__", ",".join(households)).replace("__SIMS__", ",".join(sims or []))
            .replace("__PAIRS__", ",".join(pairs or [])))


def member(text: str) -> dict:
    """'Iliana:<sdid>:<object id>:<lot id>:<age>' -> its fields."""
    f = text.split(":")
    f += ["-"] * (5 - len(f))
    return {"name": f[0], "sdid": f[1], "object": f[2], "lot": f[3], "age": f[4]}


def parse(fields: dict[tuple[str, str], list[str]]) -> dict:
    """sim_compare.run_side's fields -> {"active": member + household | None, "households": {name: {...}},
    "sims": {name: [member + household, has_home]}, "pairs": {"A+B": "<liking> <state>"|"none"|"missing"},
    "error": text | None}."""
    reading: dict = {"active": None, "households": {}, "sims": {}, "pairs": {}, "error": None}
    errors = fields.get(("-", "error"))
    if errors:
        reading["error"] = "; ".join(errors)[:400]
    active = (fields.get(("-", "active")) or ["-"])[0]
    if active != "-":
        reading["active"] = member(active.rsplit(":", 1)[0]) | {"household": active.rsplit(":", 1)[1]}
    for (name, kind), values in fields.items():
        if kind == "household":
            for value in values:
                entry = dict(pair.partition("=")[::2] for pair in value.split(";"))
                entry["members"] = [member(m) for m in entry.get("members", "").split(",") if m]
                entry["active"] = entry.get("active") == "1"
                reading["households"][name] = entry
        elif kind == "sim":
            for value in values:
                f = value.split(":")
                found = member(":".join(f[:5])) | {"household": f[5] if len(f) > 5 else "-",
                                                    "has_home": len(f) > 6 and f[6] == "1"}
                reading["sims"].setdefault(name.lower(), []).append(found)
        elif kind == "pair":
            reading["pairs"][name] = values[0]
    return reading


def read(endpoint: str, households: list[str], sims: list[str] | None = None, pairs: list[str] | None = None) -> dict:
    """One game's reading (parse) for these households, Sims and pairs."""
    import sim_compare
    PROBE.parent.mkdir(parents=True, exist_ok=True)
    PROBE.write_text(probe_text(households, sims, pairs), encoding="utf-8")
    return parse(sim_compare.run_side(endpoint, PROBE))


def pick_sim(found: list[dict]) -> dict | None:
    """Among Sims of one first name: one in the world, of a household with a home lot (a family) first."""
    ranked = sorted(found, key=lambda s: (s["object"] == "0", not s.get("has_home")))
    return ranked[0] if ranked and ranked[0]["object"] != "0" else None


_IDS: dict[str, str] = {}


def sim_id(name: str, endpoint: str = SERVER) -> str:
    """A Sim's object id on the server by first name (the Martinezes' are known; any other is read once per process).
    A name that is already an id comes back as it is. SystemExit when no such Sim is in the world."""
    if name.isdigit():
        return name
    key = name.lower()
    if key in KNOWN:
        return KNOWN[key]
    if key not in _IDS:
        reading = read(endpoint, [], [name])
        found = pick_sim(reading["sims"].get(key, []))
        if found is None:
            raise SystemExit(f"no Sim named {name} in the server's world" + (f" ({reading['error']})" if reading["error"] else ""))
        _IDS[key] = found["object"]
    return _IDS[key]


def games(choice: str) -> dict[str, str]:
    """--game: server, client1, client2, client3, HOST:PORT or all (the default: the server and players 1 and 2; a
    three-player read names client3)."""
    every = {"server": SERVER, "client 1": compare_client.CLIENT1, "client 2": compare_client.client2()}
    if choice == "all":
        return every
    if choice == "server":
        return {"server": SERVER}
    endpoint = compare_client.resolve(choice[-1] if choice in ("client1", "client2", "client3") else choice)
    return {compare_client.name(endpoint): endpoint}


def household_line(name: str, h: dict) -> str:
    members = ", ".join(f"{m['name']} ({m['age']}, sd {m['sdid']}, " + ("not in the world" if m["object"] == "0"
                        else f"id {m['object']} on lot {m['lot']}") + ")" for m in h["members"])
    return (f"  {name}{' (active)' if h['active'] else ''}: funds {h.get('funds', '?')}, home lot {h.get('home', '?')}"
            f" {h.get('address', '-')}, household id {h.get('id', '?')}; {len(h['members'])} member(s): {members}")


def summary(game: str, reading: dict) -> list[str]:
    if reading["error"]:
        return [f"{game}: error: {reading['error']}"]
    a = reading["active"]
    lines = [f"{game}: selected " + (f"{a['name']} (sd {a['sdid']}, id {a['object']}) of {a['household']}" if a else "-")]
    for name, h in sorted(reading["households"].items(), key=lambda kv: not kv[1]["active"]):
        lines.append(household_line(name, h))
    lines += [f"  {pair}: {state}" for pair, state in reading.get("pairs", {}).items()]
    return lines


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("households", nargs="*", help="households to read besides each game's active one (by name)")
    p.add_argument("--game", default="all", help="server, client1, client2, client3, HOST:PORT or all (default)")
    p.add_argument("--sim", default="", help="find a Sim by first name on the server and print its object id")
    p.add_argument("--pair", action="append", default=[], help="A+B: two Sims' relationship in each game (repeatable)")
    p.add_argument("--json", action="store_true")
    a = p.parse_args(argv)
    if a.sim:
        reading = read(SERVER, [], [a.sim])
        found = reading["sims"].get(a.sim.lower(), [])
        if a.json:
            print(json.dumps(found, indent=2))
        for s in found:
            print(f"{s['name']} of {s['household']}: id {s['object']} on lot {s['lot']}, sd {s['sdid']}, {s['age']}")
        chosen = pick_sim(found)
        print(f"sim_id {a.sim} = {chosen['object']}" if chosen else f"no {a.sim} in the world"
              + (f" ({reading['error']})" if reading["error"] else ""))
        return 0 if chosen else 1
    readings = {game: read(endpoint, a.households, None, a.pair) for game, endpoint in games(a.game).items()}
    if a.json:
        print(json.dumps(readings, indent=2))
        return 0
    for game, reading in readings.items():
        print("\n".join(summary(game, reading)))
    return 1 if any(r["error"] for r in readings.values()) else 0


if __name__ == "__main__":
    sys.exit(main())
