"""Server vs client, side by side, for the Sims you name: where they are and what they hold, show and feel.

    python scripts/sim_compare.py                      # Jennifer and Pablo
    python scripts/sim_compare.py Jennifer --props     # plus the props within 3 m (type, hidden flags, parent)
    python scripts/sim_compare.py --moodlets           # plus moodlets, and the HUD's times for the selected Sim
    python scripts/sim_compare.py Pablo --machines     # plus each state machine on the Sim and its current state
    python scripts/sim_compare.py Pablo --clients 1,2,3  # every player's game against one server read

One generated probe runs on each game; every field is printed server | client with "!" where they disagree (a position
more than 0.25 m off, a facing more than 15 degrees off, a different held object or moodlet). Object ids differ
between the games for runtime props, so held objects and props compare by type. A client's Sim shows a PuppetPosture
named after the server's posture; that counts as the same.

--client 1|2|3|HOST:PORT picks the client (default client 1, or SIMSONLINE_COMPARE_CLIENT). --clients 1,2,3 compares
several in one call: the server is read once, each client gets its own block ("### client N"), and a last line gives
each client's visible mismatch count. Exit 3 when any client has a visible mismatch.
"""
