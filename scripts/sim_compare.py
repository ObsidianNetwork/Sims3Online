def run_side(endpoint: str, probe: Path = PROBE) -> dict[tuple[str, str], list[str]]:
    out = subprocess.run([sys.executable, "scripts/bridgectl.py", "--endpoint", endpoint, "probe", str(probe.relative_to(ROOT))],
                         cwd=ROOT, capture_output=True, text=True, timeout=240).stdout
    if "-- DIAG_RUN --" not in out:
        errors = [ln.strip() for ln in out.splitlines() if "error CS" in ln or "failed" in ln]
        return {("-", "error"): errors or [out.strip()[-400:]]}
    body = out.split("-- DIAG_RUN --", 1)[-1]
    fields: dict[tuple[str, str], list[str]] = {}
    for line in body.splitlines():
        m = re.match(r"\s*([\w:.]+)\|([^|]*)\|(.*)$", line)
        if m:
            fields.setdefault((m.group(2), m.group(1)), []).append(m.group(3).strip())
        elif "err" in line and "=" in line:
            fields.setdefault(("-", "error"), []).append(line.strip())
    return fields


def differs(field: str, a: str, b: str) -> bool:
    try:
        if field == "pos":
            pa, pb = [float(v) for v in a.split(",")], [float(v) for v in b.split(",")]
            return math.dist((pa[0], pa[2]), (pb[0], pb[2])) > 0.25 or abs(pa[1] - pb[1]) > 0.3
        if field == "facing":
            fa, fb = [float(v) for v in a.split(",")], [float(v) for v in b.split(",")]
            angle = abs(math.degrees(math.atan2(fa[0], fa[1]) - math.atan2(fb[0], fb[1]))) % 360
            return min(angle, 360 - angle) > 15
        if field == "posture":
            return b.replace("Puppet:", "") != a and not (b.startswith("Puppet:") and a.startswith(b[7:]))
        if field.startswith("moodlet:"):
            # Minutes left. A client's copy keeps the server's TimeoutCount from the last moodlet line (resent every 10 s,
            # about 10 sim minutes at normal speed); the HUD time (hud=) is counted down between lines by the fork hook.
            ta, tb = float(a.split()[0]), float(b.split()[0])
            if (ta < 0) != (tb < 0) or abs(ta - tb) > 12:
                return True
            return "hud=" in a and "hud=" in b and abs(float(a.split("hud=")[1]) - float(b.split("hud=")[1])) > 5
        if field == "machines":
            # A recorder lists a machine once it has seen a state request for the Sim (none yet after a boot): an empty
            # side says nothing.
            return a not in ("-", "(none)") and b not in ("-", "(none)") and a != b
        if field == "interaction":
            return b not in ("-", "(none)")  # a client runs no interactions: one running there can animate its Sim
    except (ValueError, IndexError):
        pass
    return a != b


def machines(endpoint: str, sim_id: str) -> tuple[list[str], list[str]]:
    """machine:state per machine animating the Sim on that game (SACS_RECORDER actor), cosmetic layers and dead drivers
    (a 6th column 0: a replaced machine the recorder still remembers) left out; and machine:origin for the same rows
    (origin_rows; empty from a mod before the origin column)."""
    sys.path.insert(0, str(ROOT / "scripts"))
    import sacs_names as names
    out = subprocess.run([sys.executable, "scripts/bridgectl.py", "--endpoint", endpoint, "SACS_RECORDER", "actor", sim_id],
                         cwd=ROOT, capture_output=True, text=True, timeout=60).stdout
    return machine_rows(out, names), origin_rows(out, names)


CONFIRM_S = 1.0  # longer than the stream lag (a release reaches a client 0.06-0.5 s after the server's, 2026-10-31)


def read_machines(sim_id: str, endpoints: list[str]) -> dict[str, tuple[list[str], list[str]]]:
    """machines() of every game at once (threads), so a driver released between two reads does not show on one side
    only: one bridge call after another put about a second between the server's read and a client's."""
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max_workers=len(endpoints)) as pool:
        return dict(zip(endpoints, pool.map(lambda endpoint: machines(endpoint, sim_id), endpoints)))


def machine_fields(sim: str, sim_id: str, sides: list[tuple[dict, str]], reader=read_machines, wait=None) -> None:
    """The machines and origins fields of each side. When a client's machines differ from the server's, every game is
    read again after CONFIRM_S: a difference in both reads is the one compared (it fails); one that the second read no
    longer has (a release or acquire in flight between the games, shower 2026-10-31) stays visible as "machines (first
    read)", never counted. A lifetime difference longer than CONFIRM_S still fails."""
    endpoints = [endpoint for _, endpoint in sides]
    first = reader(sim_id, endpoints)
    rows = first
    text = {endpoint: " ".join(first[endpoint][0]) or "-" for endpoint in endpoints}
    server_ep = endpoints[0]
    if any(text[endpoint] != text[server_ep] for endpoint in endpoints[1:]):
        (wait or __import__("time").sleep)(CONFIRM_S)
        rows = reader(sim_id, endpoints)
        again = {endpoint: " ".join(rows[endpoint][0]) or "-" for endpoint in endpoints}
        for side, endpoint in sides:
            if text != again:
                side[(sim, "machines (first read)")] = [text[endpoint]]
    for side, endpoint in sides:
        side[(sim, "machines")] = [" ".join(rows[endpoint][0]) or "-"]
        if rows[endpoint][1]:
            side[(sim, "origins")] = ["; ".join(rows[endpoint][1])]


def machine_rows(out: str, names) -> list[str]:
    """The live, non-cosmetic rows of a SACS_RECORDER actor reply as machine:state, sorted. Two live drivers in the same
    state stay visible as "machine:state x2" (2026-10-21: a second Idle driver in standing_idle beside the copy's own
    read as one row, and a crumpled pose with it)."""
    import replay_check  # the one parser of actor rows (its drivers check reads the same rows)
    counts: dict[str, int] = {}
    for f in replay_check.actor_rows(out):
        if f["alive"] and not f["cosmetic"]:
            row = f"{names.name64(int(f['machine'], 16))}:{names.name32(f['state'])}"
            counts[row] = counts.get(row, 0) + 1
    return [row if n == 1 else f"{row} x{n}" for row, n in sorted(counts.items())]


def origin_rows(out: str, names) -> list[str]:
    """machine:origin for each live, non-cosmetic driver (SACS_RECORDER actor's 7th column: replay, a mod path such as
    repair, game via its callers, adopted), sorted; none from a mod before the column. Shown, never a mismatch: the
    server's drivers are the game's own and a client's the replay's."""
    import replay_check
    return sorted(f"{names.name64(int(f['machine'], 16))}:{f['origin']}" for f in replay_check.actor_rows(out)
                  if f["alive"] and not f["cosmetic"] and f.get("origin"))


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("sims", nargs="*", default=["Jennifer", "Pablo"])
    p.add_argument("--props", action="store_true")
    p.add_argument("--moodlets", action="store_true")
    p.add_argument("--machines", action="store_true", help="each state machine on the Sim and its current state (both recorders)")
    p.add_argument("--client", default="", help="the client game to compare: 1 (default), 2 (player 2) or HOST:PORT")
    p.add_argument("--clients", default="", help="several clients against one server read, comma-separated (1,2,3)")
    p.add_argument("--known", action="append", default=[],
                   help="a field (interaction, posture, prop:X, ...; comma-separated or repeated) whose mismatch is a known defect the "
                        "scenario names: shown as k, not counted as visible")
    a = p.parse_args(argv)
    if a.client and a.clients:
        p.error("--client and --clients: give one")
    if a.client:
        ENDPOINTS["client"] = compare_client.use(a.client)
    try:
        chosen = list(dict.fromkeys(compare_client.resolve(c) for c in a.clients.split(",") if c.strip())) or [ENDPOINTS["client"]]
    except ValueError as ex:
        p.error(str(ex))
    source = TEMPLATE.replace("__NAMES__", ",".join(a.sims)).replace("__PROPS__", "true" if a.props else "false") \
        .replace("__MOODLETS__", "true" if a.moodlets else "false")
    sys.path.insert(0, str(ROOT / "scripts"))
    import probe_source
    probe = probe_source.write(PROBE, source)  # its own file: a concurrent call cannot overwrite it before it compiles
    server = run_side(ENDPOINTS["server"], probe)
    clients = {endpoint: run_side(endpoint, probe) for endpoint in chosen}
    for errors in [server.get(("-", "error"))] + [client.get(("-", "error")) for client in clients.values()]:
        if errors:
            print("probe error:", errors)
    if a.machines:
        ids = {"jennifer": "18031287978496800304", "pablo": "18031287978496800272"}
        sides = [(server, ENDPOINTS["server"])] + [(client, endpoint) for endpoint, client in clients.items()]
        for name in a.sims:
            sim_id = ids.get(name.lower())
            if sim_id:
                machine_fields(name.capitalize(), sim_id, sides)
    counts = {}
    for endpoint, client in clients.items():
        if len(clients) > 1:
            print(f"### {compare_client.name(endpoint)} ({endpoint})")
        counts[endpoint] = report(server, client, {f.strip() for k in a.known for f in k.split(",") if f.strip()})
    if len(clients) > 1:
        print("per client: " + "; ".join(f"{compare_client.name(e)}: {n} visible mismatch(es)" for e, n in counts.items()))
    return 0 if not any(counts.values()) else 3


def report(server: dict, client: dict, known: set[str] | None = None) -> int:
    """Print one client's fields against the server's; its visible mismatch count. A field in known (a defect the
    scenario names, --known) is shown as k and not counted."""
    keys = list(dict.fromkeys(list(server) + list(client)))
    mismatches = 0
    for sim in dict.fromkeys(k[0] for k in keys):
        print(f"== {sim}" if sim != "-" else "== game")
        for key in [k for k in keys if k[0] == sim]:
            field = key[1]
            if field == "error":
                continue
            sv, cv = server.get(key, ["(none)"]), client.get(key, ["(none)"])
            if field.startswith("prop:"):
                sv, cv = sorted(sv), sorted(cv)
            a_text, b_text = "; ".join(sv), "; ".join(cv)
            bad = differs(field, a_text, b_text)
            # Logic-layer fields (what the client's game believes, not what it shows): a client has no socializing
            # posture (the HUD reads the server's through the fork hooks). "~" there, "!" for what the player sees, and
            # for an interaction running on a client at all (it runs none; one there animates its copy on its own).
            logic_only = field in ("posture", "slotParent")
            # The selected Sim is each player's own choice (the server's game selects whoever its last pick acted with), and
            # the plumbbob hangs over each game's selected Sim (phone-standing and phone-seated, 2026-10-17: FAIL on the
            # plumbbob alone when the two games had different Sims selected).
            per_player = field in ("selected", "prop:PlumbBob")
            if field in ("origins", "machines (first read)"):  # information, never a mismatch
                print(f"    {field:<26} {a_text:<44} | {b_text}")
                continue
            is_known = field in (known or ())
            mismatches += bad and not logic_only and not per_player and not is_known
            mark = (" ~" if logic_only else " =" if per_player else " k" if is_known else " !") if bad else "  "
            label = field.replace("moodlet:", "moodlet ").replace("prop:", "prop ")
            print(f" {mark} {label:<26} {a_text:<44} | {b_text}")
    print(f"{mismatches} visible mismatch(es)  (! visible, ~ logic layer only, = each player's own, k a known defect)")
    return mismatches


if __name__ == "__main__":
    sys.exit(main())
